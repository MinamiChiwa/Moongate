    /// <summary>
    /// 请求失败的界面说明：后端错误码经 <see cref="Reason"/>；连接失败、超时与其他异常给出中文概括，不显示英文异常消息与类型名。
    /// 前端自己抛出的中文说明（<see cref="InvalidOperationException"/> 等的消息含中文）原样采用。
    /// </summary>
    public static string Error(Exception error) => error switch
    {
        MabiTool.Client.MabiToolApiException api => Reason(api.Problem?.Code ?? $"http.{api.Status}"),
        HttpRequestException => UiText.Pick("无法连接后端", "無法連接後端"),
        TaskCanceledException or TimeoutException => UiText.Pick("请求超时", "請求逾時"),
        OperationCanceledException => UiText.Pick("请求已取消", "請求已取消"),
        UnauthorizedAccessException => UiText.Pick("没有访问权限", "沒有存取權限"),
        IOException => Readable(error.Message) ?? UiText.Pick("读写文件失败", "讀寫檔案失敗"),
        _ => Readable(error.Message) ?? UiText.Pick("请求未完成", "請求未完成")
    };

    /// <summary>
    /// 后端或系统给出的说明能否直接显示：含中文且不夹带英文标识（点号连接的码、异常类型名）时原样返回，否则为空，由调用方改用原因码的文案。
    /// </summary>
    public static string? Readable(string? text)
    {
        if (string.IsNullOrWhiteSpace(text) || !text.Any(IsChinese)) return null;
        foreach (var token in text.Split([' ', '（', '）', '(', ')', '：', ':', '，', ',', '。', '；', ';', '、'], StringSplitOptions.RemoveEmptyEntries))
            if (token.Length > 3 && token.All(c => c < 128) && (token.Contains('.') || token.Contains("Exception", StringComparison.Ordinal)) && token.Any(char.IsLetter))
                return null;
        return text.Trim();
    }

    private static bool IsChinese(char c) => c is >= '一' and <= '鿿';

