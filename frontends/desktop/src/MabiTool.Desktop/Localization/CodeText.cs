        408 or 504 => UiText.Pick("后端处理超时", "後端處理逾時"),
        409 => UiText.Pick("内容已被修改", "內容已被修改"),
        429 => UiText.Pick("请求过于频繁", "請求過於頻繁"),
        503 => UiText.Pick("后端暂时不可用", "後端暫時不可用"),
        >= 500 => UiText.Pick("后端内部出错", "後端內部出錯"),
        _ => UiText.Pick("后端拒绝了请求", "後端拒絕了請求")
    };

    private static string? Lookup(Dictionary<string, (string Hans, string Hant)> table, string? key) =>
        key is not null && table.TryGetValue(key, out var text) ? UiText.Pick(text.Hans, text.Hant) : null;

    /// <summary>
    /// 没有文案的标识：只给简短的中文概括，原文记入待补清单（诊断页列出）；没有原文时只给概括。
    /// 各模块自己的文案表（染色阶段、引擎原因等）的缺省分支也经这里，类别名写进清单便于区分来源。
    /// </summary>
    public static string Unknown(string category, string? raw, string hans, string hant)
    {
        if (raw is { Length: > 0 } && unmapped.TryAdd(category + ":" + raw, 0)) UnmappedChanged?.Invoke(null, EventArgs.Empty);
        return UiText.Pick(hans, hant);
    }

    private static Dictionary<string, (string Hans, string Hant)> Table(params (string Code, string Hans, string Hant)[] rows)
    {
        var table = new Dictionary<string, (string Hans, string Hant)>(rows.Length, StringComparer.Ordinal);
        foreach (var (code, hans, hant) in rows) table.Add(code, (hans, hant));
        return table;
    }
