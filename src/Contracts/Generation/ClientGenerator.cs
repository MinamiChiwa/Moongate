export class MabiToolApiError extends Error {
  constructor(readonly status: number, readonly problem: ApiProblem | null) {
    super('Local API request failed (' + status + ')'); this.name = 'MabiToolApiError';
  }
}
export interface ApiResponseMetadata { readonly status: number; readonly etag: string | null; readonly location: string | null; }
function localEndpoint(value: string): URL {
  const url = new URL(value);
  if (url.protocol !== 'http:' || !['127.0.0.1', 'localhost'].includes(url.hostname) ||
      !url.port || url.username || url.password || url.search || url.hash || url.pathname !== '/')
    throw new TypeError('An explicit loopback HTTP origin is required');
  return url;
}
function moduleId(id: string): string {
  if (!/^[a-z][a-z0-9-]{0,63}(?![\s\S])/.test(id)) throw new TypeError('Module ID is invalid');
  return id;
}
function resourceId(id: string): string {
  if (!/^[A-Za-z0-9._-]{1,128}(?![\s\S])/.test(id)) throw new TypeError('Resource ID is invalid');
  return id;
}
async function readJson(response: Response, limit = 4 * 1024 * 1024): Promise<unknown> {
  const reader = response.body?.getReader();
  if (!reader) throw new Error('Local API response is empty');
  let length = 0; const parts: Uint8Array[] = [];
  try {
    for (;;) {
      const next = await reader.read();
      if (next.done) break;
      length += next.value.byteLength;
      if (length > limit) throw new Error('Local API response exceeds size limit');
      parts.push(next.value);
    }
  } finally { await reader.cancel(); reader.releaseLock(); }
  const bytes = new Uint8Array(length); let offset = 0;
  for (const part of parts) { bytes.set(part, offset); offset += part.length; }
  try { return JSON.parse(new TextDecoder('utf-8', { fatal: true }).decode(bytes)); }
  catch { throw new Error('Local API response is invalid JSON'); }
}
function isProblem(value: unknown, status: number): value is ApiProblem {
  if (!value || typeof value !== 'object') return false;
  const p = value as Partial<ApiProblem>;
  return p.status === status && typeof p.code === 'string' && typeof p.messageKey === 'string' &&
    typeof p.traceId === 'string' && typeof p.type === 'string' && typeof p.title === 'string' &&
    typeof p.retryable === 'boolean' && !!p.details && typeof p.details === 'object';
}
