    if (authenticated) request.Headers.Authorization = new AuthenticationHeaderValue("Bearer", await token(ct));
    if (idempotencyKey is not null) request.Headers.Add("Idempotency-Key", idempotencyKey);
    if (ifMatch is not null) request.Headers.Add("If-Match", ifMatch);
    AddEventHeaders(request, options);
    if (body is not null) {
      request.Content = new ByteArrayContent(body);
      request.Content.Headers.ContentType = new MediaTypeHeaderValue("application/json");
    }
    request.Headers.Accept.ParseAdd("application/json, application/schema+json");
    using var response = await http.SendAsync(request, HttpCompletionOption.ResponseHeadersRead, ct);
    var limit = response.IsSuccessStatusCode ? maximumResponseBytes : 4 * 1024 * 1024;
    await using var stream = await response.Content.ReadAsStreamAsync(ct);
    using var buffer = new MemoryStream();
    var block = new byte[16384];
    int count;
    while ((count = await stream.ReadAsync(block, ct)) != 0) {
      if (buffer.Length + count > limit) throw new InvalidDataException("Local API response exceeds size limit");
      buffer.Write(block, 0, count);
    }
    if (!response.IsSuccessStatusCode) {
      ApiProblem? problem = null;
      if (response.Content.Headers.ContentType?.MediaType == "application/problem+json") {
        try { problem = JsonSerializer.Deserialize<ApiProblem>(buffer.ToArray(), ContractJson.Options); }
        catch (JsonException) { }
        if (problem?.Status != (int)response.StatusCode) problem = null;
      }
      throw new MabiToolApiException((int)response.StatusCode, problem);
    }
    var value = JsonSerializer.Deserialize<T>(buffer.ToArray(), ContractJson.Options)
      ?? throw new JsonException("Local API response is empty");
    onResponse?.Invoke(new((int)response.StatusCode, response.Headers.ETag?.ToString(), response.Headers.Location?.ToString()));
    return value;
  }
