    public static string TypeScript()
    {
        var output = new StringBuilder("// 此文件由 C# 公共契约生成。\n");
        foreach (var type in ContractSchemas.ReachableTypes())
        {
            var name = ContractSchemas.Name(type);
            if (type.IsGenericType && type.GetGenericTypeDefinition() == typeof(OpenEnum<>))
            {
                output.AppendLine($"export type {name} = {ContractSchemas.Name(type.GenericTypeArguments[0])} | (string & {{}});");
                continue;
            }
            if (type == typeof(UInt64String))
