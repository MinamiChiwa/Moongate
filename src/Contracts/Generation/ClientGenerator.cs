                var schema = ContractSchemas.Export(type)["properties"]![wireName];
                output.AppendLine($"  readonly {wireName}: {TsType(property.PropertyType, schema)};");
            }
            output.AppendLine("}");
        }
        output.AppendLine(TypeScriptRuntime);
        output.AppendLine(TypeScriptBinaryRuntime);
        output.AppendLine("export class MabiToolClient {");
        output.AppendLine("  private readonly baseUrl: URL;");
