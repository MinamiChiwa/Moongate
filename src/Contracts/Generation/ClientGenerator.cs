    private static string CsType(Type type) => type.IsGenericType
        ? type.Name[..type.Name.IndexOf('`')] + "<" + string.Join(", ", type.GetGenericArguments().Select(CsType)) + ">"
        : type.Name;

    private static string TsType(Type type, System.Text.Json.Nodes.JsonNode? schema = null)
    {
        var nullable = Nullable.GetUnderlyingType(type);
        if (nullable is not null) return TsType(nullable) + " | null";
        string result;
        if (type == typeof(string) || type == typeof(DateTimeOffset)) result = "string";
        else if (type == typeof(bool)) result = "boolean";
        else if (type == typeof(JsonElement)) result = "unknown";
        else if (type == typeof(byte) || type == typeof(sbyte) || type == typeof(short) || type == typeof(ushort) ||
                 type == typeof(int) || type == typeof(uint) || type == typeof(double) ||
                 type == typeof(float) || type == typeof(decimal)) result = "number";
        else if (type == typeof(long) || type == typeof(ulong))
            throw new InvalidOperationException("公共 64 位整数必须使用 UInt64String：" + type);
        else if (type.IsGenericType && type.GetGenericTypeDefinition() == typeof(IReadOnlyList<>))
            result = "ReadonlyArray<" + TsType(type.GenericTypeArguments[0], schema?["items"]) + ">";
        else if (type.IsGenericType && type.GetGenericTypeDefinition() == typeof(IReadOnlyDictionary<,>))
            result = "Readonly<Record<string, " + TsType(type.GenericTypeArguments[1], schema?["additionalProperties"] is System.Text.Json.Nodes.JsonObject values ? values : null) + ">>";
        else result = ContractSchemas.Name(type);
        return !type.IsValueType && schema is System.Text.Json.Nodes.JsonObject obj &&
            obj["type"] is System.Text.Json.Nodes.JsonArray types && types.Any(t => t?.GetValue<string>() == "null")
            ? result + " | null" : result;
    }

