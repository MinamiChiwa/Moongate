    private const string TypeScriptGet = """
  private async request<T>(path: string, method: string, body: unknown, authenticated: boolean, idempotencyKey?: string, ifMatch?: string, signal?: AbortSignal, onResponse?: (metadata: ApiResponseMetadata) => void, options?: EventStreamOptions, maximumResponseBytes = 4 * 1024 * 1024): Promise<T> {
    const headers: Record<string, string> = { 'Accept': 'application/json, application/schema+json' };
    if (authenticated) headers['Authorization'] = 'Bearer ' + await this.token();
    if (body !== undefined) headers['Content-Type'] = 'application/json';
    if (idempotencyKey !== undefined) headers['Idempotency-Key'] = idempotencyKey;
    if (ifMatch !== undefined) headers['If-Match'] = ifMatch;
    Object.assign(headers, this.eventHeaders(options));
    const response = await this.transport(new URL(path, this.baseUrl), {
      method, headers, body: body === undefined ? undefined : JSON.stringify(body),
      signal, redirect: 'error', credentials: 'omit', cache: 'no-store'
    });
    if (!response.ok) {
      let problem: ApiProblem | null = null;
      if (response.headers.get('content-type')?.split(';')[0] === 'application/problem+json') {
        try {
          const body = await readJson(response);
          if (isProblem(body, response.status)) problem = body;
        } catch { if (signal?.aborted) throw signal.reason; }
      } else { await response.body?.cancel(); }
      throw new MabiToolApiError(response.status, problem);
    }
    const value = await readJson(response, maximumResponseBytes) as T;
    onResponse?.({ status: response.status, etag: response.headers.get('etag'), location: response.headers.get('location') });
    return value;
  }
""";

