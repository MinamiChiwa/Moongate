"""精准策略的采集端口；输入实现由统一代理提供。"""
from pathlib import Path
from typing import Any, Protocol


class NativeRuntime(Protocol):
    def check(self) -> None: ...
    def resolve_target(self, target: Any, *, server: str | None, check: Any) -> Any: ...
    def activate_target(self, target: Any, *, check: Any) -> bool: ...
    def prepare(self, pid: int, folder: Path, check: Any, hwnd: int) -> tuple[Any, dict]: ...
    def enable_server_input(self, backend: Any, server: str) -> None: ...
    def require_input_capability(self, backend: Any) -> None: ...
    def collect(self, backend: Any, *, wait_seconds: float, session_seconds: float,
                check: Any, event: Any) -> dict: ...
    def load_session(self, folder: str) -> dict: ...
    def create_io(self, backend: Any, baseline: dict, folder: Path, *, stop: Any) -> Any: ...
